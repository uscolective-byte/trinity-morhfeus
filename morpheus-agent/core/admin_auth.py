"""Owner authentication for the standalone Morpheus service."""
import base64
import binascii
import hmac
import os
from fastapi import HTTPException, Request
from core.config import domain_settings


async def require_admin(request: Request):
    expected = os.getenv('MORPHEUS_ADMIN_TOKEN', '')
    if not expected.strip():
        raise HTTPException(503, 'Morpheus administration is not configured')
    authorization = request.headers.get('authorization', '')
    scheme, _, value = authorization.partition(' ')
    token = ''
    if scheme.lower() == 'bearer':
        token = value
    elif scheme.lower() == 'basic':
        try:
            user, _, token = base64.b64decode(value, validate=True).decode('utf-8').partition(':')
            if user != 'owner':
                token = ''
        except (ValueError, UnicodeError, binascii.Error):
            token = ''
    if not token or not hmac.compare_digest(token.encode(), expected.encode()):
        raise HTTPException(401, 'Owner authentication required', headers={'WWW-Authenticate': 'Basic realm="Morpheus", charset="UTF-8"'})
    origin = request.headers.get('origin')
    # The public origin is configured independently of TLS termination and
    # request-controlled Host / Forwarded headers.
    if origin and origin.rstrip('/') != domain_settings.base_url.rstrip('/'):
        raise HTTPException(403, 'Cross-origin administration is forbidden')


async def require_oauth_admin(request: Request):
    # Provider callbacks prove possession of a one-use state generated by an owner.
    if request.method == 'GET' and request.url.path.endswith('/callback'):
        return
    await require_admin(request)
